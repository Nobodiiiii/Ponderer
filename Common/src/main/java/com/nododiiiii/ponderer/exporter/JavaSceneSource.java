package com.nododiiiii.ponderer.exporter;

import com.google.gson.*;
import com.nododiiiii.ponderer.runtime.api.JavaScene;
import com.nododiiiii.ponderer.scene.*;
import net.minecraft.core.BlockPos;
import net.minecraft.world.phys.Vec3;
import java.lang.reflect.*;
import java.util.*;

/**
 * Reads the data-building Java emitted by JavaSceneSources, without compiling or executing host code.
 * Unsupported Java is an error: a half-parsed document must never replace a working scene.
 */
public final class JavaSceneSource {
    static final String NOTICE = "// Auto-generated by The Ponderer. JavaScene data calls can be edited and reloaded in game.\n"
        + "// 由思索者生成。可手改 JavaScene 数据调用并在游戏内重载；完整导出会检查手改冲突。\n";
    private static final Gson GSON = new GsonBuilder()
        .registerTypeAdapter(LocalizedText.class, new LocalizedText.GsonAdapter()).create();
    private record Token(String text, int start, int end) {}
    private record Body(String name, int start, int end, int first, int last) {}
    private final String source;
    private final String scope;
    private final List<Token> tokens = new ArrayList<>();
    private final Map<String, Body> bodies = new LinkedHashMap<>();
    private final Set<String> evaluating = new HashSet<>();

    private JavaSceneSource(String source, String scope) {
        this.source = source;
        this.scope = scope;
        lex();
        for (int i = 2; i + 3 < tokens.size(); i++) {
            if (!Set.of("DslScene", "SceneSegment", "LocalizedText").contains(at(i - 1))
                || !at(i + 1).equals("(")) continue;
            int close = matching(i + 1, "(", ")");
            if (!at(close + 1).equals("{")) continue;
            int end = matching(close + 1, "{", "}");
            int start = i - 1;
            while (start > 0 && !Set.of(";", "{", "}").contains(at(start - 1))) start--;
            int from = tokens.get(start).start;
            int line = source.lastIndexOf('\n', from - 1) + 1;
            if (source.substring(line, from).isBlank()) from = line;
            Body body = new Body(at(i), from, tokens.get(end).end, close + 2, end);
            if (bodies.putIfAbsent(body.name, body) != null)
                throw new IllegalArgumentException("Overloaded scene data method: " + body.name);
            i = end;
        }
        if (!bodies.containsKey("loadDocument")) throw new IllegalArgumentException("Missing loadDocument()");
    }

    public static DslScene read(String source, String sceneId) {
        JavaSceneSource reader = new JavaSceneSource(source, sceneId);
        Object value = reader.method("loadDocument");
        if (!(value instanceof DslScene document) || !sceneId.equals(document.id))
            throw new IllegalArgumentException("Java scene identity must remain " + sceneId);
        return SceneCodec.withAnchors(document);
    }

    /** Replace data methods only; keep the host runtime, extension installation and other handwritten methods. */
    public static String write(String source, DslScene document) {
        JavaSceneSource reader = new JavaSceneSource(source, document.id);
        reader.method("loadDocument"); // Validate every referenced method before replacing anything.
        List<Body> replaced = reader.bodies.values().stream()
            .filter(body -> body.name.equals("text") || body.name.equals("loadDocument")
                || reader.atMethodType(body).equals("SceneSegment")).sorted(Comparator.comparingInt(Body::start)).toList();
        StringBuilder result = new StringBuilder(source);
        for (int i = replaced.size() - 1; i >= 0; i--) {
            Body body = replaced.get(i);
            result.replace(body.start, body.end, i == 0 ? JavaSceneSources.members(document).stripTrailing() : "");
        }
        String rendered = result.toString();
        String legacyNotice = "// Auto-generated by The Ponderer — do not edit; will be overwritten on next export.\n"
            + "// 由思索者自动生成 — 请勿手动修改；下次导出时会被覆盖。\n";
        // Old exports carry a misleading source-editing notice. Preserve the original line endings otherwise.
        String normalized = rendered.replace("\r\n", "\n");
        if (normalized.startsWith(legacyNotice)) {
            int secondLine = rendered.indexOf('\n', rendered.indexOf('\n') + 1);
            rendered = NOTICE + rendered.substring(secondLine + 1);
        }
        read(rendered, document.id);
        return rendered;
    }

    private String atMethodType(Body body) {
        for (int i = 1; i < tokens.size(); i++)
            if (tokens.get(i).start >= body.start && at(i).equals(body.name) && at(i + 1).equals("("))
                return at(i - 1);
        return "";
    }

    private Object method(String name) {
        Body body = bodies.get(name);
        if (body == null || !evaluating.add(name)) throw new IllegalArgumentException("Unsupported or recursive method " + name);
        try { return new Evaluation(body).run(); }
        finally { evaluating.remove(name); }
    }

    private final class Evaluation {
        private final Map<String, Object> variables = new HashMap<>();
        private final Body body;
        private int pos;
        Evaluation(Body body) { this.body = body; this.pos = body.first; }
        private String peek() { return at(pos); }
        private boolean take(String value) { if (!peek().equals(value)) return false; pos++; return true; }
        private void expect(String value) { if (!take(value)) throw error("Expected " + value); }
        private IllegalArgumentException error(String message) {
            int offset = pos < tokens.size() ? tokens.get(pos).start : source.length();
            long line = source.substring(0, offset).chars().filter(c -> c == '\n').count() + 1;
            return new IllegalArgumentException(body.name + ":" + line + ": " + message + " near " + peek());
        }
        Object run() {
            while (pos < body.last) {
                if (take(";")) continue;
                if (take("return")) {
                    Object result = expression();
                    expect(";");
                    if (pos != body.last) throw error("Statements after return are not supported");
                    return result;
                }
                int start = pos, equal = pos;
                while (equal < body.last && !Set.of("=", ";", "(").contains(at(equal))) equal++;
                if (at(equal).equals("=")) {
                    String name = at(equal - 1);
                    List<String> target = tokens.subList(start, equal).stream().map(Token::text).toList();
                    pos = equal + 1;
                    Object value = expression();
                    if (target.size() >= 3 && target.get(target.size() - 2).equals(".")
                        && variables.containsKey(target.get(0))) {
                        if (target.size() != 3) throw error("Unsupported field assignment");
                        setField(variables.get(target.get(0)), name, value);
                    } else variables.put(name, value);
                    expect(";");
                } else {
                    pos = start;
                    expression();
                    expect(";");
                }
            }
            throw error("Missing return");
        }
        private Object expression() {
            Object value;
            boolean negative = take("-");
            String token = peek();
            if (token.startsWith("\"")) { pos++; value = GSON.fromJson(token, String.class); }
            else if (take("null")) value = null;
            else if (take("true")) value = true;
            else if (take("false")) value = false;
            else if (!token.isEmpty() && Character.isDigit(token.charAt(0))) {
                pos++;
                String number = token.replace("_", "");
                char suffix = Character.toLowerCase(number.charAt(number.length() - 1));
                if (suffix == 'f') value = Float.parseFloat(number.substring(0, number.length() - 1));
                else if (suffix == 'd') value = Double.parseDouble(number.substring(0, number.length() - 1));
                else if (suffix == 'l') value = Long.decode(number.substring(0, number.length() - 1));
                else if (number.contains(".") || number.contains("e") || number.contains("E")) value = Double.parseDouble(number);
                else value = Integer.decode(number);
            } else if (take("new")) {
                String type = qualified();
                if (take("<")) { while (!take(">")) { if (pos >= body.last) throw error("Unclosed type"); pos++; } }
                value = construct(type, arguments());
            } else {
                String name = qualified();
                if (peek().equals("(")) value = call(name, arguments());
                else if (variables.containsKey(name)) value = variables.get(name);
                else if (name.equals("BlockPos.ZERO")) value = BlockPos.ZERO;
                else if (name.equals("Vec3.ZERO")) value = Vec3.ZERO;
                else throw error("Unsupported value " + name);
            }
            if (negative) {
                if (!(value instanceof Number n)) throw error("Expected a number");
                if (value instanceof Integer) value = -n.intValue();
                else if (value instanceof Long) value = -n.longValue();
                else if (value instanceof Float) value = -n.floatValue();
                else value = -n.doubleValue();
            }
            while (take(".")) {
                String name = peek(); pos++;
                value = invoke(value, name, arguments());
            }
            return value;
        }
        private String qualified() {
            StringBuilder name = new StringBuilder(peek()); pos++;
            while (peek().equals(".") && !at(pos + 2).equals("(")) {
                pos++; name.append('.').append(peek()); pos++;
            }
            // Static calls and a variable's first method share the same lexical shape.
            if (peek().equals(".")) { pos++; name.append('.').append(peek()); pos++; }
            return name.toString();
        }
        private List<Object> arguments() {
            expect("(");
            List<Object> args = new ArrayList<>();
            if (!take(")")) {
                do { args.add(expression()); } while (take(","));
                expect(")");
            }
            return args;
        }
        private Object call(String name, List<Object> args) {
            if (name.equals("text") && args.size() == 1) return LocalizedText.ref(scope, (String) args.getFirst());
            if (bodies.containsKey(name) && args.isEmpty()) return method(name);
            int dot = name.lastIndexOf('.');
            if (dot > 0 && variables.containsKey(name.substring(0, dot)))
                return invoke(variables.get(name.substring(0, dot)), name.substring(dot + 1), args);
            String simple = name.replace("java.util.", "").replace("com.google.gson.", "")
                .replace("com.nododiiiii.ponderer.scene.", "");
            return switch (simple) {
                case "List.of", "Arrays.asList" -> new ArrayList<>(args);
                case "Map.entry" -> new AbstractMap.SimpleImmutableEntry<>(args.get(0), args.get(1));
                case "Map.ofEntries" -> {
                    Map<Object, Object> map = new LinkedHashMap<>();
                    for (Object arg : args) { var entry = (Map.Entry<?, ?>) arg; map.put(entry.getKey(), entry.getValue()); }
                    yield map;
                }
                case "Map.of" -> {
                    if (args.size() % 2 != 0) throw error("Map.of expects pairs");
                    Map<Object, Object> map = new LinkedHashMap<>();
                    for (int i = 0; i < args.size(); i += 2) map.put(args.get(i), args.get(i + 1));
                    yield map;
                }
                case "LocalizedText.ref" -> LocalizedText.ref((String) args.get(0), (String) args.get(1));
                case "LocalizedText.of" -> LocalizedText.of((String) args.getFirst());
                case "LocalizedText.ofMap" -> GSON.fromJson(GSON.toJsonTree(args.getFirst()), LocalizedText.class);
                case "JsonParser.parseString" -> JsonParser.parseString((String) args.getFirst());
                default -> throw error("Unsupported Java call " + name);
            };
        }
    }

    private static Object construct(String name, List<Object> args) {
        name = name.replace("net.minecraft.core.", "").replace("net.minecraft.world.phys.", "")
            .replace("com.nododiiiii.ponderer.scene.", "").replace("com.google.gson.", "");
        return switch (name) {
            case "JavaScene" -> new JavaScene((String) args.get(0), (LocalizedText) args.get(1));
            case "BlockPos" -> new BlockPos(((Number) args.get(0)).intValue(), ((Number) args.get(1)).intValue(), ((Number) args.get(2)).intValue());
            case "Vec3" -> new Vec3(((Number) args.get(0)).doubleValue(), ((Number) args.get(1)).doubleValue(), ((Number) args.get(2)).doubleValue());
            case "JsonObject" -> new JsonObject();
            case "JsonArray" -> new JsonArray();
            default -> {
                if (!args.isEmpty()) throw new IllegalArgumentException("Unsupported constructor " + name);
                try {
                    String dataType = name;
                    Class<?> type = name.equals("DslScene") ? DslScene.class : Arrays.stream(DslScene.class.getClasses())
                        .filter(c -> ("DslScene." + c.getSimpleName()).equals(dataType)).findFirst().orElseThrow();
                    yield type.getConstructor().newInstance();
                } catch (ReflectiveOperationException error) { throw new IllegalArgumentException("Unsupported data constructor " + name, error); }
            }
        };
    }
    private static Object invoke(Object target, String name, List<Object> args) {
        if (target instanceof JsonElement json && args.isEmpty()) return switch (name) {
            case "getAsJsonObject" -> json.getAsJsonObject();
            case "getAsJsonArray" -> json.getAsJsonArray();
            default -> throw new IllegalArgumentException("Unsupported JSON conversion " + name);
        };
        if (!(target instanceof JavaScene || target instanceof JavaScene.Step))
            throw new IllegalArgumentException("Only JavaScene data-building calls can be reloaded");
        for (Method method : target.getClass().getMethods()) {
            if (method.getDeclaringClass() == Object.class || !method.getName().equals(name) || method.getParameterCount() != args.size()) continue;
            try {
                Object[] converted = new Object[args.size()];
                for (int i = 0; i < converted.length; i++) converted[i] = convert(args.get(i), method.getGenericParameterTypes()[i]);
                return method.invoke(target, converted);
            } catch (ReflectiveOperationException error) { throw new IllegalArgumentException("Invalid scene call " + name, error); }
        }
        throw new IllegalArgumentException("Unknown scene action " + name);
    }
    private static Object convert(Object value, Type type) {
        if (value == null) return null;
        if (type instanceof Class<?> cls && cls.isInstance(value)) return value;
        return GSON.fromJson(GSON.toJsonTree(value), type);
    }
    private static void setField(Object target, String name, Object value) {
        if (target == null || !(target instanceof DslScene || target.getClass().getEnclosingClass() == DslScene.class))
            throw new IllegalArgumentException("Unsupported field target");
        try {
            Field field = target.getClass().getField(name);
            if (Modifier.isStatic(field.getModifiers()) || Modifier.isFinal(field.getModifiers())) throw new IllegalArgumentException("Read-only field " + name);
            field.set(target, convert(value, field.getGenericType()));
        } catch (ReflectiveOperationException error) { throw new IllegalArgumentException("Invalid scene field " + name, error); }
    }
    private String at(int i) { return i < 0 || i >= tokens.size() ? "" : tokens.get(i).text; }
    private int matching(int start, String open, String close) {
        int depth = 0;
        for (int i = start; i < tokens.size(); i++) {
            if (at(i).equals(open)) depth++;
            if (at(i).equals(close)) { depth--; if (depth == 0) return i; }
        }
        throw new IllegalArgumentException("Unclosed " + open);
    }
    private void lex() {
        for (int i = 0; i < source.length();) {
            char c = source.charAt(i);
            if (Character.isWhitespace(c)) { i++; continue; }
            if (source.startsWith("//", i)) { int end = source.indexOf('\n', i); i = end < 0 ? source.length() : end; continue; }
            if (source.startsWith("/*", i)) { int end = source.indexOf("*/", i + 2); if (end < 0) throw new IllegalArgumentException("Unclosed comment"); i = end + 2; continue; }
            int start = i++;
            if (c == '"') {
                boolean closed = false;
                while (i < source.length()) {
                    char next = source.charAt(i++);
                    if (next == '\\') { i++; continue; }
                    if (next == '"') { closed = true; break; }
                }
                if (!closed) throw new IllegalArgumentException("Unclosed Java string");
            } else if (Character.isJavaIdentifierStart(c)) {
                while (i < source.length() && Character.isJavaIdentifierPart(source.charAt(i))) i++;
            } else if (Character.isDigit(c)) {
                while (i < source.length()) {
                    char next = source.charAt(i);
                    if (Character.isLetterOrDigit(next) || next == '.' || next == '_'
                        || ((next == '+' || next == '-') && "eE".indexOf(source.charAt(i - 1)) >= 0)) i++;
                    else break;
                }
            }
            tokens.add(new Token(source.substring(start, i), start, i));
        }
    }
}
